import { execFileSync } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import pg from 'pg'

const repositoryRoot = resolve(import.meta.dirname, '..')
export const baselinePath = 'apps/hub/migrations/0001_baseline.sql'
const roleRegisterPath = 'contracts/technical/hub-database-roles.json'

export const OWNER_ROLES = Object.freeze([
  'iam_owner',
  'workspace_owner',
  'project_owner',
  'registry_owner',
  'builder_owner',
  'model_connection_owner',
])

// Migrations 001 to 059 left these behind. None of them may be written by the baseline, and the
// renderer refuses a dump that still carries one rather than filtering it out of sight.
export const SUPERSEDED_ROLES = Object.freeze([
  'brain_owner',
  'claude_connection_owner',
  'connections_owner',
  'hub_prj03_command',
  'hub_r2_brain_attester',
  'hub_r2_brain_bootstrap',
  'hub_r2_brain_read',
  'hub_r2_connections',
  'hub_r2_key_conformance_subject',
  'hub_r2_project_binding',
  'hub_rb_executor',
  'hub_rb_ingress',
  'hub_s2_read',
  'hub_s3_read',
  'hub_s4_baseline_command',
  'hub_s4_baseline_read',
  'hub_s6_inception_command',
  'hub_ws01_command',
])

const fail = (code, detail = '') => {
  throw new Error(`${code}${detail ? `:${detail}` : ''}`)
}

export const readLoginRoles = (root = repositoryRoot) =>
  JSON.parse(readFileSync(resolve(root, roleRegisterPath), 'utf8')).roles.map((entry) => entry.role)

// CREATE only, never ALTER: a role that already exists on the cluster keeps the password and
// attributes it was provisioned with, and two databases created at once on one cluster race into
// duplicate_object rather than into each other's role definition.
const renderRolePreamble = (loginRoles) =>
  [...loginRoles.map((role) => [role, 'LOGIN']), ...OWNER_ROLES.map((role) => [role, 'NOLOGIN'])]
    .map(([role, login]) =>
      `DO $$ BEGIN\n  CREATE ROLE "${role}" ${login} NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;`)
    .join('\n')

const header = `-- The Hub's baseline schema. This one file creates the whole catalog: the eight capability
-- roles of contracts/technical/hub-database-roles.json, the six owner roles, and every schema,
-- table, function, trigger, constraint, index and grant the product has.
-- Generated by scripts/generate-hub-baseline.mjs, which applies this file to a throwaway database,
-- reads it back with pg_dump --schema-only and re-renders it. Run that script with --check to prove
-- the committed bytes are what it produces; never edit this file by hand.`

// pg_dump emits a random token on its \restrict and \unrestrict meta-command lines and the pg
// client cannot parse either, so both go. Comment lines go with them: they carry pg_dump's own
// version string, which would make the file change when the dump binary is upgraded.
export const renderBaseline = (rawDump, loginRoles) => {
  const kept = rawDump
    .split('\n')
    .filter((line) => !line.startsWith('\\restrict') && !line.startsWith('\\unrestrict'))
  const body = kept.join('\n').replace(/^--.*$/gm, '').replace(/\n{3,}/g, '\n\n').trim()
  const offenders = SUPERSEDED_ROLES.filter((role) => new RegExp(`\\b${role}\\b`).test(body))
  if (offenders.length > 0) fail('BASELINE_SUPERSEDED_ROLE_REFUSED', offenders.join(','))
  return `BEGIN;\n\n${header}\n\n${renderRolePreamble(loginRoles)}\n\n${body}\n\nCOMMIT;\n`
}

const readAdmin = () => {
  const read = (name) => process.env[name] ?? fail(`MISSING_CONFIG_${name}`)
  return {
    host: read('CONEXUS_TEST_DB_HOST'),
    port: Number(read('CONEXUS_TEST_DB_PORT')),
    database: read('CONEXUS_TEST_DB_NAME'),
    user: read('CONEXUS_TEST_DB_USER'),
    password: read('CONEXUS_TEST_DB_PASSWORD'),
  }
}

const connectionStringFor = (admin, database) => {
  const url = new URL('postgresql://localhost')
  url.hostname = admin.host
  url.port = String(admin.port)
  url.pathname = `/${database}`
  url.username = admin.user
  url.password = admin.password
  return url.toString()
}

// pg_dump refuses a server newer than itself, and this repository's server is 17.10 while several
// Linux images still ship a 16 client. CONEXUS_PG_DUMP names a binary; CONEXUS_TEST_DB_CONTAINER
// names a docker container to run the server's own pg_dump inside. Neither reachable is a refusal,
// not a silent skip.
export const dumpSchema = (admin, database) => {
  const container = process.env.CONEXUS_TEST_DB_CONTAINER
  if (container) {
    return execFileSync('docker', ['exec', container, 'pg_dump', '-U', admin.user, '--schema-only', '-d', database], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  }
  const binary = process.env.CONEXUS_PG_DUMP ?? 'pg_dump'
  try {
    return execFileSync(binary, ['--schema-only', '--dbname', connectionStringFor(admin, database)], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
  } catch (error) {
    fail('BASELINE_PG_DUMP_UNAVAILABLE', `${binary}: ${String(error.message).split('\n')[0]}`)
  }
}

const withThrowawayDatabase = async (admin, body) => {
  const owner = new pg.Client(admin)
  await owner.connect()
  const database = `conexus_baseline_${process.pid}_${randomUUID().replaceAll('-', '').slice(0, 8)}`
  try {
    await owner.query(`CREATE DATABASE "${database}"`)
    return await body(database)
  } finally {
    await owner.query(`DROP DATABASE IF EXISTS "${database}" WITH (FORCE)`)
    await owner.end()
  }
}

const applySql = async (connectionString, sql) => {
  const client = new pg.Client({ connectionString })
  await client.connect()
  try {
    await client.query(sql)
  } finally {
    await client.end()
  }
}

// The baseline is its own source. Applying it and dumping the result must reproduce it byte for
// byte, which is what makes the committed file reviewable: it is a fixed point, not a transcript.
export const regenerateBaseline = async (admin = readAdmin(), root = repositoryRoot) => {
  const committed = readFileSync(resolve(root, baselinePath), 'utf8')
  return withThrowawayDatabase(admin, async (database) => {
    await applySql(connectionStringFor(admin, database), committed)
    return renderBaseline(dumpSchema(admin, database), readLoginRoles(root))
  })
}

const isEntrypoint = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isEntrypoint) {
  const target = resolve(repositoryRoot, baselinePath)
  const rendered = await regenerateBaseline()
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== rendered) fail('BASELINE_DRIFT', baselinePath)
    process.stdout.write(`${JSON.stringify({ verdict: 'CURRENT', file: baselinePath, lines: rendered.split('\n').length })}\n`)
  } else {
    writeFileSync(target, rendered)
    process.stdout.write(`${JSON.stringify({ verdict: 'WRITTEN', file: baselinePath, lines: rendered.split('\n').length })}\n`)
  }
}
