import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(import.meta.dirname, '..')
const manifestPath = 'runtime/r1/.conexus/s2-ownership-manifest.json'
const receiptPath = 'runtime/r1/.conexus/s2-generation-receipt.json'
const outputPath = 'apps/hub/src/generated/r1-new-project-seed.ts'
const expectedManifestDigest = 'f3a132e9ab3ef6e682ebf25da73f0318e2a55b74c53557d1957241fe2b6d1242'
const expectedReceiptDigest = 'f505e67f1e31f2f94ab7268e31dee6882f5e0d58975b878f3e2ecbdb8aa487e7'
const seed = Object.freeze([
  Object.freeze({ class: 'GENERATED', sourcePath: 'runtime/r1/generated/r1/operations.json', path: 'generated/r1/operations.json', digest: '6d86a8c7ffd04138c4ed051f99bc36a5dc06fe327848dde49b7ec0d505a436f7' }),
  Object.freeze({ class: 'GENERATED', sourcePath: 'runtime/r1/generated/r1/operations.mjs', path: 'generated/r1/operations.mjs', digest: 'e7c0f68c5e44b0062000bbdcd84d7d2d44d4ee407babd7d34a11433a3748e5bf' }),
  Object.freeze({ class: 'PLATFORM-CONTRACT', sourcePath: 'runtime/r1/platform/r1/contract.json', path: 'platform/r1/contract.json', digest: 'bca5ab767f98e3260af9c3838693d5e238553a0875a80282617754d62f18dd9c' }),
])

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex')
const gitObjectId = (type, bytes) => createHash('sha1').update(Buffer.concat([Buffer.from(`${type} ${bytes.length}\0`), bytes])).digest('hex')
const read = (root, path) => readFileSync(resolve(root, path))

const gitTreeId = (entries) => {
  const tree = {}
  for (const entry of entries) {
    let node = tree
    const parts = entry.path.split('/')
    for (const part of parts.slice(0, -1)) node = node[part] ??= {}
    node[parts.at(-1)] = { oid: gitObjectId('blob', Buffer.from(entry.bytesBase64, 'base64')) }
  }
  const render = (node) => {
    const body = Buffer.concat(Object.entries(node).sort(([left], [right]) => left.localeCompare(right)).map(([name, value]) => {
      const directory = !('oid' in value)
      const oid = directory ? render(value) : value.oid
      return Buffer.concat([Buffer.from(`${directory ? '40000' : '100644'} ${name}\0`), Buffer.from(oid, 'hex')])
    }))
    return gitObjectId('tree', body)
  }
  return render(tree)
}

export function buildR1S3NewProjectSeed(root = repositoryRoot) {
  const manifestBytes = read(root, manifestPath)
  const receiptBytes = read(root, receiptPath)
  if (sha256(manifestBytes) !== expectedManifestDigest) throw new Error('S3_NEW_SEED_MANIFEST_DIGEST_REFUSED')
  if (sha256(receiptBytes) !== expectedReceiptDigest) throw new Error('S3_NEW_SEED_RECEIPT_DIGEST_REFUSED')
  const manifest = JSON.parse(manifestBytes.toString('utf8'))
  if (!Array.isArray(manifest.entries)) throw new Error('S3_NEW_SEED_MANIFEST_SHAPE_REFUSED')
  if (manifest.entries.some((entry) => entry.class === 'APP-OWNED')) throw new Error('S3_NEW_SEED_APP_OWNED_REFUSED')

  const entries = seed.map((expected) => {
    const manifestEntry = manifest.entries.find((entry) => entry.path === expected.sourcePath)
    if (!manifestEntry || manifestEntry.class !== expected.class || manifestEntry.outputDigest !== expected.digest) {
      throw new Error(`S3_NEW_SEED_CUSTODY_REFUSED:${expected.sourcePath}`)
    }
    const bytes = read(root, expected.sourcePath)
    if (sha256(bytes) !== expected.digest) throw new Error(`S3_NEW_SEED_BYTES_REFUSED:${expected.sourcePath}`)
    return Object.freeze({ class: expected.class, path: expected.path, sha256: expected.digest, bytesBase64: bytes.toString('base64') })
  })

  const expectedTree = gitTreeId(entries)
  const commitBytes = Buffer.from(`tree ${expectedTree}\nauthor Conexus OS <source@conexus.invalid> 946684800 +0000\ncommitter Conexus OS <source@conexus.invalid> 946684800 +0000\n\nConexus OS R1 NEW seed\n`)
  return Object.freeze({
    kind: 'conexus.r1-s3-new-project-seed/v1',
    ownershipManifestSha256: expectedManifestDigest,
    generationReceiptSha256: expectedReceiptDigest,
    appOwnedPathCount: 0,
    expectedTree,
    expectedSourceRevision: gitObjectId('commit', commitBytes),
    entries,
  })
}

export function renderR1S3NewProjectSeed(root = repositoryRoot) {
  return `// Generated by scripts/generate-r1-s3-new-project-seed.mjs. Do not edit.\nexport const R1_NEW_PROJECT_SEED = ${JSON.stringify(buildR1S3NewProjectSeed(root), null, 2)} as const\n`
}

export function checkR1S3NewProjectSeed(root = repositoryRoot) {
  const expected = renderR1S3NewProjectSeed(root)
  const actual = readFileSync(resolve(root, outputPath), 'utf8')
  if (actual !== expected) throw new Error('S3_NEW_SEED_GENERATED_DRIFT')
  return buildR1S3NewProjectSeed(root)
}

function main() {
  if (process.argv.includes('--check')) {
    checkR1S3NewProjectSeed()
    process.stdout.write('{"verification":"PASS","entries":3,"appOwnedPathCount":0}\n')
    return
  }
  writeFileSync(resolve(repositoryRoot, outputPath), renderR1S3NewProjectSeed())
}

if (resolve(process.argv[1] ?? '') === resolve(fileURLToPath(import.meta.url))) main()
