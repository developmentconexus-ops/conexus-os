const EXPECTED_API = `// Generated by Conexus from conexus/manifest.json. Every check and build rewrites this file; do not edit it.
import { z } from 'zod'
import { ConexusError } from './failures.gen'

export const schemas = {
  addItem: {
    input: z.strictObject({ name: z.string().min(2) }),
    output: z.strictObject({ id: z.number().int(), tags: z.array(z.string()).optional() }),
  },
  listItems: {
    input: z.strictObject({ category: z.string().min(1).max(80), page: z.number().int().min(1).optional(), active: z.boolean().optional() }),
    output: z.array(z.strictObject({ id: z.number().int(), name: z.string(), price: z.number().min(0).max(1000000), note: z.string().max(200).optional() })).max(500),
  },
} as const

export type OperationId = keyof typeof schemas
export type Input<K extends OperationId> = z.infer<(typeof schemas)[K]['input']>
export type Output<K extends OperationId> = z.infer<(typeof schemas)[K]['output']>

const failure = (status: number, body: string): ConexusError => {
  try {
    const parsed: unknown = JSON.parse(body)
    if (typeof parsed === 'object' && parsed !== null) {
      const { code, detail } = parsed as { code?: unknown; detail?: unknown }
      if (typeof code === 'string') return new ConexusError(code, typeof detail === 'string' ? detail : '')
    }
  } catch {}
  return new ConexusError(\`HTTP_\${status}\`, body.slice(0, 500))
}

const call = async <K extends OperationId>(id: K, input: Input<K>): Promise<Output<K>> => {
  const response = await fetch(\`/__conexus/api/\${id}\`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify(input),
  })
  const body = await response.text()
  if (!response.ok) throw failure(response.status, body)
  return JSON.parse(body) as Output<K>
}

export const api = {
  addItem: (input: Input<'addItem'>) => call('addItem', input),
  listItems: (input: Input<'listItems'>) => call('listItems', input),
} as const
`

